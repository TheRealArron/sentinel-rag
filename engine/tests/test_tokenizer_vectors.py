"""The estimator, held against the tokenizer it is a model of.

`lang.estimate_tokens` approximates multilingual-e5's SentencePiece tokenizer
without importing it, because the chunker has to work with nothing installed and
chunk ids must not change depending on whether `transformers` is present. The
cost of that is a model which can drift from the thing it models in silence:
nine of 93 child chunks were built past the 512-token input limit and truncated
at embed time, and every test in the suite still passed, because every test that
touched a budget measured it with the same estimator that was wrong.

So the real tokenizer's answers are committed, the way the Go/Python Sigma and
IOC bridges commit theirs, and these tests hold the two together with no
dependency on the model being installed. Regenerate with `make tokenizer-check`
after changing chunking, the estimator, or the corpus.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from sentinel.lang import estimate_tokens

VECTORS = Path(__file__).parent / "testdata" / "tokenizer_vectors.json"

# How far the estimate is allowed to fall short of the real count.
#
# The observed worst case on this corpus is 1.062. The budget that matters is
# child_tokens=400 against a 512-token model limit, which is 28% of headroom, so
# an estimate short by a tenth still cannot produce a truncated chunk. Tightening
# this to the observed value would fail on the first document that tokenises
# slightly worse; loosening it past ~1.28 would stop protecting anything.
CALIBRATION_BOUND = 1.10


@pytest.fixture(scope="module")
def bundle() -> dict:
    return json.loads(VECTORS.read_text(encoding="utf-8"))


class TestTokenizerAgreement:
    def test_the_bundle_is_present_and_describes_its_provenance(self, bundle):
        assert bundle["vectors"], "no vectors committed"
        assert bundle["model"].startswith("intfloat/multilingual-e5")
        assert bundle["max_seq_length"] == 512
        assert bundle["chunk_settings"]["child_tokens"] > 0

    def test_no_chunk_reaches_the_model_input_limit(self, bundle):
        """The defect itself: chunks silently truncated at embed time.

        These are the longest chunks the corpus produces, measured with the real
        tokenizer. If one reaches 512 its tail is dropped before it is ever
        embedded, and nothing anywhere else in the suite would notice.
        """
        limit = bundle["max_seq_length"]
        over = [v for v in bundle["vectors"] if v["real_tokens"] >= limit]
        assert not over, (
            f"{len(over)} chunk(s) at or past the {limit}-token limit, "
            f"longest {max(v['real_tokens'] for v in over)} — these are truncated when embedded"
        )

    def test_the_estimator_still_produces_the_committed_estimates(self, bundle):
        """Drift check, and the reason this file is not circular.

        Every other budget test measures a chunk with the same estimator that
        produced it, so an estimator that is wrong agrees with itself. This one
        compares against numbers generated by the real tokenizer, so changing the
        estimator without regenerating the vectors fails here.
        """
        drifted = [
            (v["estimate"], estimate_tokens(v["text"]), v["text"][:60])
            for v in bundle["vectors"]
            if estimate_tokens(v["text"]) != v["estimate"]
        ]
        assert not drifted, (
            f"{len(drifted)} vector(s) no longer match the committed estimate, e.g. "
            f"{drifted[0][0]} -> {drifted[0][1]} for {drifted[0][2]!r}. "
            "Regenerate with `make tokenizer-check`."
        )

    def test_the_estimator_does_not_underestimate_beyond_its_headroom(self, bundle):
        """Underestimating is the direction that overruns the model's input."""
        bad = [
            (v["real_tokens"], v["estimate"], v["real_tokens"] / max(v["estimate"], 1))
            for v in bundle["vectors"]
            if v["real_tokens"] > v["estimate"] * CALIBRATION_BOUND
        ]
        assert not bad, (
            f"{len(bad)} vector(s) underestimate by more than {CALIBRATION_BOUND:.2f}x, "
            f"worst real={bad[0][0]} estimate={bad[0][1]} ratio={bad[0][2]:.3f}"
        )

    def test_the_headroom_under_the_limit_is_recorded_and_still_positive(self, bundle):
        """The margin is empirical, not structural, and it is thin.

        `child_tokens` bounds the *body*. The title and the overlap tail are
        added afterwards, so the embedded string's estimate runs past the budget
        — the largest pinned vector estimates 502 against a 400-token budget. At
        the observed worst ratio that arithmetic permits about 529 real tokens,
        which is past the limit. It does not happen, because the chunks that run
        longest are ones the estimator overestimates, and the measured maximum is
        497 of 512.

        So nothing here proves a chunk cannot breach the limit. What this asserts
        is the measurement: the longest chunk the corpus currently produces still
        fits, with the margin named. Adding documents can consume it, which is
        why `make tokenizer-check` has to be re-run when the corpus changes — it
        is the only thing that would notice.
        """
        limit = bundle["max_seq_length"]
        longest = bundle["corpus_max_real_tokens"]
        assert 0 < longest < limit, f"longest chunk {longest} does not fit under {limit}"
        headroom = limit - longest
        assert headroom >= 10, (
            f"only {headroom} token(s) of headroom under the {limit}-token limit "
            f"(longest chunk {longest}). The next document could truncate."
        )
